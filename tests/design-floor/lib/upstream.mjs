// Nguồn của bộ đo design-floor. Từ bước 2 (hồ sơ design-floor-vendor-va-ban-va-a) bộ đo chấm BẢN VENDORED
// trong kit (`chuanBiNguon`) và bản gói giao đi; đường lấy bản ghim qua mạng (`layUpstream`) chỉ còn cho
// `dong-bo.mjs` và `rao-dong.mjs --write` — tức khi đổi ghim hoặc đổi bản vá.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { GOC_KIT } from './hop-dong.mjs';

const require = createRequire(import.meta.url);

export function esbuild() {
  try {
    return require('esbuild');
  } catch {
    throw new Error('thiếu esbuild — chạy: npm ci --prefix tests/design-floor');
  }
}

function sh(cmd, args, cwd) {
  return execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

export function thuMucCache(hd) {
  return process.env.DESIGN_FLOOR_CACHE || join(tmpdir(), 'design-floor-upstream', hd.nguon.commit);
}

// Bản ghim upstream qua mạng (sparse + depth 1) vào một cache theo commit. Cache chỉ được dùng khi dấu
// `.xong` ghi đúng commit + tập lấy về; dở dang thì xoá làm lại. DESIGN_FLOOR_KHONG_MANG=1 chặn hẳn đường
// này — CI đặt biến đó để chứng bộ đo không lấy mã qua mạng.
export function layUpstream(hd) {
  if (process.env.DESIGN_FLOOR_KHONG_MANG) {
    throw new Error('DESIGN_FLOOR_KHONG_MANG=1 — không lấy mã upstream qua mạng');
  }
  const dir = thuMucCache(hd);
  const dau = join(dir, '.xong');
  const ky = `${hd.nguon.commit} ${hd.nguon.lay_ve.join(' ')}`;
  if (existsSync(dau) && readFileSync(dau, 'utf8').trim() === ky) return dir;
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  sh('git', ['init', '-q'], dir);
  sh('git', ['remote', 'add', 'origin', `${hd.nguon.repo}.git`], dir);
  sh('git', ['sparse-checkout', 'set', '--no-cone', ...hd.nguon.lay_ve], dir);
  sh('git', ['fetch', '-q', '--depth', '1', '--filter=blob:none', 'origin', hd.nguon.commit], dir);
  sh('git', ['checkout', '-q', 'FETCH_HEAD'], dir);
  const head = sh('git', ['rev-parse', 'HEAD'], dir).trim();
  if (head !== hd.nguon.commit) throw new Error(`lấy về ${head}, ghim ${hd.nguon.commit}`);
  sh('npm', ['ci', '--omit=dev', '--ignore-scripts', '--workspaces=false', '--no-audit', '--no-fund'], dir);
  writeFileSync(dau, `${ky}\n`);
  return dir;
}

// Bản vendored trong kit — nguồn của mọi phép đo. Không có nhánh lấy mạng: vắng thì là lỗi có tên.
export function chuanBiNguon(hd, gocKit = GOC_KIT) {
  const dir = join(gocKit, hd.vendor.goc);
  if (!existsSync(join(dir, 'src'))) {
    throw new Error(`thiếu bản vendored ở ${hd.vendor.goc} — chạy: node tests/design-floor/dong-bo.mjs --write`);
  }
  return dir;
}

// Bản gói giao đi: vỏ của kit + đóng kín + gói npm ghim ở tests/design-floor, gói thành một tệp ESM.
// Dựng với gốc làm việc = gốc kit nên chú thích đường trong bản gói là đường tương đối trong kit — cùng
// bố cục thì cùng byte ở mọi chỗ checkout. preserveSymlinks để bản sao bố cục (node_modules là liên kết)
// cho đúng đường như bản thật.
export const DAU_BAN_GOI = '// GENERATED by tests/design-floor/dong-bo.mjs --write from design-floor/vo/ui.ts + design-floor/vendor/design-os — do not edit.';

export function dungBanGoi(hd, gocVao = GOC_KIT) {
  const gocKit = realpathSync(gocVao);
  const r = esbuild().buildSync({
    absWorkingDir: gocKit,
    entryPoints: [hd.vendor.vo],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    outfile: hd.vendor.ban_goi,
    write: false,
    logLevel: 'error',
    nodePaths: [join(gocKit, 'tests', 'design-floor', 'node_modules')],
    preserveSymlinks: true,
    banner: { js: DAU_BAN_GOI },
  });
  return Buffer.from(r.outputFiles[0].contents);
}

export function bam(duong) {
  return createHash('sha256').update(readFileSync(duong)).digest('hex');
}

export function bamBuf(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

export function soDong(duong) {
  return readFileSync(duong, 'utf8').split('\n').length;
}

// Đóng kín của MỘT điểm vào: mọi tệp của kho upstream esbuild kéo theo — src/ và cả JSON nhập
// từ schemas/ — (import chỉ-kiểu bị bỏ như lúc chạy) và mọi import ngoài (builtin node + gói npm).
export async function dongKin(goc, entry) {
  const r = await esbuild().build({
    absWorkingDir: goc,
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    packages: 'external',
    write: false,
    metafile: true,
    logLevel: 'silent',
  });
  const tep = Object.keys(r.metafile.inputs).filter((f) => !f.startsWith('node_modules/')).sort();
  const ngoai = new Set();
  for (const i of Object.values(r.metafile.inputs)) for (const im of i.imports) if (im.external) ngoai.add(im.path);
  return { tep, ngoai: [...ngoai].sort() };
}

// Đóng kín của VỎ trên một gốc upstream bất kỳ (bản ghim, bản dựng lại trước-vá, bản vendored): lời nhập
// `…/vendor/design-os/<đường>` của vỏ được chuyển sang `<goc>/<đường>`, nên cùng một tệp vỏ đo được trên
// mọi gốc. Chỉ giữ tệp nằm trong gốc — tệp vỏ là của kit, không thuộc danh sách chép.
export async function dongKinVo(gocVao, voTuyetDoi) {
  // Đường thật: esbuild khoá đường theo realpath, còn lời chuyển hướng dựng từ đường đưa vào (macOS: /var ↔ /private/var).
  const goc = realpathSync(gocVao);
  const doi = {
    name: 'vo-vendor',
    setup(b) {
      b.onResolve({ filter: /(^|\/)vendor\/design-os\// }, (a) => {
        const sau = a.path.slice(a.path.indexOf('vendor/design-os/') + 'vendor/design-os/'.length);
        return { path: join(goc, sau.replace(/\.js$/, '.ts')) };
      });
    },
  };
  const r = await esbuild().build({
    absWorkingDir: goc,
    entryPoints: [voTuyetDoi],
    bundle: true,
    platform: 'node',
    format: 'esm',
    packages: 'external',
    write: false,
    metafile: true,
    logLevel: 'silent',
    plugins: [doi],
  });
  const tep = Object.keys(r.metafile.inputs).filter((f) => !f.startsWith('..') && !f.startsWith('/') && !f.startsWith('node_modules/')).sort();
  const ngoaiTheoTep = {};
  for (const [f, i] of Object.entries(r.metafile.inputs)) {
    if (f.startsWith('..') || f.startsWith('/')) continue;
    ngoaiTheoTep[f] = i.imports.filter((im) => im.external).map((im) => im.path);
  }
  return { tep, ngoaiTheoTep };
}

// Mã không chú thích — để phép quét token mạng không bắt nhầm lời giải thích (bài học `-an`).
export function boChuThich(duong) {
  const loader = /\.json$/.test(duong) ? 'json' : /\.tsx$/.test(duong) ? 'tsx' : 'ts';
  return esbuild().transformSync(readFileSync(duong, 'utf8'), { loader, legalComments: 'none' }).code;
}

// Áp (hoặc đảo) một tệp diff của sổ vá lên một thư mục upstream. git apply chạy được ngoài kho git.
export function apVa(dir, tepVa, { nguoc = false } = {}) {
  execFileSync('git', ['apply', ...(nguoc ? ['-R'] : []), '--whitespace=nowarn', resolve(tepVa)], {
    cwd: dir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

// Đường của tệp mà một tệp diff chạm, đọc từ dòng `--- a/<đường>` và `+++ b/<đường>` — tệp bản vá tạo chỉ có vế
// `+++` (vế kia là /dev/null), tệp bản vá xoá chỉ có vế `---`.
export function tepCuaVa(tepVa) {
  return [...new Set([...readFileSync(tepVa, 'utf8').matchAll(/^(?:---|\+\+\+) [ab]\/(\S+)/gm)].map((m) => m[1]))].sort();
}

export function duongTuongDoi(p) {
  return relative(GOC_KIT, p) || '.';
}
